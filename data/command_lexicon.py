def stop_phrases():
    """멈춤 표현 전체 (완성형 + 어간에 어미를 붙인 형태)."""
    return STOP_COMPLETE + [stem + STOP_STEM_ENDING for stem in STOP_STEMS]


def korean_to_number(korean):
    """한글 숫자를 정수로 변환"""
    if not korean:
        return 0

    if korean in KOREAN_NUMBERS:
        return KOREAN_NUMBERS[korean]

    if "십" in korean:
        ten_digit, _, one_digit = korean.partition("십")
        value = KOREAN_NUMBERS[ten_digit] * 10 if ten_digit else 10
        if one_digit in KOREAN_NUMBERS:
            value += KOREAN_NUMBERS[one_digit]
        return value

    return 0


